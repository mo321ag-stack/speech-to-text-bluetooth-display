String formOf({required bool joinsNext, required bool joinsPrev}) =>
    joinsNext && joinsPrev ? 'm' : joinsNext ? 'n' : joinsPrev ? 'f' : 'i';

/// 8 CGRAM row bytes (low 5 bits, bit 4 = leftmost pixel) for a letter in a form.
List<int> glyphRows(String base, {required bool joinsNext, required bool joinsPrev}) {
  final forms = kArabicFont[base];
  if (forms == null) throw ArgumentError('No glyph for $base');
  final want = formOf(joinsNext: joinsNext, joinsPrev: joinsPrev);
  final order = {
    'i': ['i'],
    'n': ['n', 'i'],
    'm': ['m', 'n', 'i'],
    'f': ['f', 'i'],
  }[want]!;
  final used = order.firstWhere(forms.containsKey);
  final rows = forms[used]!;

  final out = <int>[];
  for (var r = 0; r < 8; r++) {
    var v = 0;
    for (var c = 0; c < 5; c++) {
      if (rows[r][c] == '#') v |= 1 << (4 - c);
    }
    out.add(v);
  }
  // A fallback drawing may lack the joining stroke: add it on the baseline.
  if (used != want) {
    if (joinsNext) out[kBaselineRow] |= 0x10;
    if (joinsPrev) out[kBaselineRow] |= 0x01;
  }
  return out;
}
