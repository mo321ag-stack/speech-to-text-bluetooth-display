/// ASCII replacement for a character the LCD can show via its ROM, or null.
String? toLcdAscii(int cp) {
  if (cp >= 0x20 && cp <= 0x7E) return String.fromCharCode(cp);
  return kLatinFold[cp] ?? kCyrillic[cp] ?? kGreek[cp];
}

bool isHebrew(int cp) => cp >= 0x0590 && cp <= 0x05FF;

/// Characters that are never drawn (emoji, symbols, control characters).
bool isDroppable(int cp) =>
    cp < 0x20 ||
    (cp >= 0x1F000 && cp <= 0x1FAFF) || // emoji
    (cp >= 0x2600 && cp <= 0x27BF) || // misc symbols, dingbats
    (cp >= 0xFE00 && cp <= 0xFE0F) || // variation selectors
    cp == 0x200D ||
    cp == 0x200E ||
    cp == 0x200F ||
    cp == 0x00A0;

/// Scripts that can only be shown by automatic rasterisation.
bool needsRaster(int cp) {
  if (toLcdAscii(cp) != null || isDroppable(cp)) return false;
  if (cp >= 0x0600 && cp <= 0x06FF) return false; // Arabic block: handled by the Arabic font
  if (cp >= 0x0300 && cp <= 0x036F) return false; // combining accents: dropped
  return true;
}

/// Letter pairs that transliterate differently from their single letters.
String preTransliterate(String text) => text
    .replaceAll('ου', 'ou')
    .replaceAll('ού', 'ou')
    .replaceAll('Ου', 'Ou')
    .replaceAll('ΟΥ', 'OU')
    .replaceAll('μπ', 'b')
    .replaceAll('ντ', 'd');
